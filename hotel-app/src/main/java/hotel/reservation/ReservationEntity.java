package hotel.reservation;

import hotel.room.RoomEntity;
import hotel.user.UserEntity;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.temporal.ChronoUnit;

/**
 * A reservation as it is stored in the database (table "reservation").
 * Replaces the old in-memory classes hotel.model.Reservation and ReservationStore.
 * Dates and status are only changed through ReservationService, which checks the rules.
 */
@Entity
@Table(name = "reservation")
public class ReservationEntity {

    /** Generated by the database (auto increment). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Foreign key room_number -> room. A room with reservations cannot be deleted. */
    @ManyToOne(optional = false)
    @JoinColumn(name = "room_number", nullable = false)
    private RoomEntity room;

    /** Foreign key customer_id -> app_user: the ID of the customer is his userId. */
    @ManyToOne(optional = false)
    @JoinColumn(name = "customer_id", nullable = false)
    private UserEntity customer;

    @Column(nullable = false)
    private LocalDate checkIn;

    @Column(nullable = false)
    private LocalDate checkOut;

    @Column(nullable = false)
    private int guests;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private ReservationStatus status = ReservationStatus.PENDING;

    /** Needed by JPA. */
    protected ReservationEntity() {
    }

    ReservationEntity(RoomEntity room, UserEntity customer, LocalDate checkIn, LocalDate checkOut, int guests) {
        this.room = room;
        this.customer = customer;
        this.checkIn = checkIn;
        this.checkOut = checkOut;
        this.guests = guests;
    }

    public Long getId() {
        return id;
    }

    public RoomEntity getRoom() {
        return room;
    }

    public UserEntity getCustomer() {
        return customer;
    }

    public LocalDate getCheckIn() {
        return checkIn;
    }

    public LocalDate getCheckOut() {
        return checkOut;
    }

    public int getGuests() {
        return guests;
    }

    public ReservationStatus getStatus() {
        return status;
    }

    public long nights() {
        return ChronoUnit.DAYS.between(checkIn, checkOut);
    }

    /** Price per night of the room x number of nights. */
    public BigDecimal totalPrice() {
        return room.getPricePerNight().multiply(BigDecimal.valueOf(nights()));
    }

    void setDates(LocalDate checkIn, LocalDate checkOut) {
        this.checkIn = checkIn;
        this.checkOut = checkOut;
    }

    void setStatus(ReservationStatus status) {
        this.status = status;
    }
}
